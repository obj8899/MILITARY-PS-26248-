// Generates src/index.light.css from src/index.css: every colour literal gets its
// lightness inverted (hue and saturation kept) and each rule is scoped to
// :root[data-theme="light"]. Re-run after editing src/index.css:  node scripts/gen-light-theme.mjs
import fs from "node:fs";
import postcss from "postcss";

const src = fs.readFileSync("src/index.css", "utf8");
const root = postcss.parse(src);
const out = postcss.root();

function hslToRgb(h, s, l) {
  const a = s * Math.min(l, 1 - l);
  const f = (n) => { const k = (n + h / 30) % 12; return l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)); };
  return [f(0), f(8), f(4)].map((v) => Math.round(v * 255));
}
function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  let h = 0, s = 0;
  if (d) {
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h *= 60;
  }
  return [h, s, l];
}
// invert lightness; keep a little contrast headroom so surfaces are off-white, text near-black
function flip(r, g, b) {
  const [h, s, l] = rgbToHsl(r, g, b);
  let nl = 1 - l;
  nl = 0.03 + nl * 0.94;
  return hslToRgb(h, s, nl);
}
function mapColours(value) {
  return value
    .replace(/#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b/g, (m, hex) => {
      let h = hex; if (h.length === 3) h = h.split("").map((c) => c + c).join("");
      const r = parseInt(h.slice(0, 2), 16), g = parseInt(h.slice(2, 4), 16), b = parseInt(h.slice(4, 6), 16);
      const [nr, ng, nb] = flip(r, g, b);
      const a = h.length === 8 ? h.slice(6, 8) : "";
      return "#" + [nr, ng, nb].map((v) => v.toString(16).padStart(2, "0")).join("") + a;
    })
    .replace(/rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)/g, (m, r, g, b, a) => {
      const [nr, ng, nb] = flip(+r, +g, +b);
      return a === undefined ? `rgb(${nr}, ${ng}, ${nb})` : `rgba(${nr}, ${ng}, ${nb}, ${a})`;
    });
}
const hasColour = (v) => /#[0-9a-fA-F]{3,8}\b|rgba?\(/.test(v);
const scope = (sel) => sel.split(",").map((s) => {
  s = s.trim();
  if (s === ":root") return ':root[data-theme="light"]';
  if (s === "html") return ':root[data-theme="light"]';
  if (s.startsWith(":root")) return s.replace(":root", ':root[data-theme="light"]');
  if (s === "body" || s.startsWith("body")) return ':root[data-theme="light"] ' + s;
  return ':root[data-theme="light"] ' + s;
}).join(", ");

function convert(rule) {
  const decls = [];
  rule.walkDecls((d) => {
    if (d.parent !== rule) return;
    if (/shadow|^filter$|backdrop-filter/.test(d.prop)) return; // keep dark shadows dark
    if (hasColour(d.value)) decls.push(d.clone({ value: mapColours(d.value), important: d.important }));
  });
  if (!decls.length) return null;
  const r = postcss.rule({ selector: scope(rule.selector) });
  decls.forEach((d) => r.append(d));
  return r;
}
root.each((node) => {
  if (node.type === "rule") { const r = convert(node); if (r) out.append(r); }
  else if (node.type === "atrule" && node.name === "media") {
    const m = postcss.atRule({ name: "media", params: node.params });
    node.each((n) => { if (n.type === "rule") { const r = convert(n); if (r) m.append(r); } });
    if (m.nodes?.length) out.append(m);
  }
});
const header = "/* GENERATED by scripts/gen-light-theme.mjs from index.css — do not edit by hand. */\n";
fs.writeFileSync("src/index.light.css", header + out.toString() + `
:root[data-theme="light"] { color-scheme: light; }
:root[data-theme="light"] .atmosphere { opacity: 0.55; }
`);
console.log("rules:", out.nodes.length);
